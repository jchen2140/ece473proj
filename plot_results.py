"""Date comparison and predicted-vs-actual plots from evaluate.py outputs.

Reads data/results/scored_rows.csv. Reuses evaluate.COLUMN / LABEL / contract_losses /
bootstrap so the figures match the scored tables. Writes figures and extra CSVs under
data/results/.
"""
from collections import defaultdict

import matplotlib

matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

import evaluate
from collect_nyc import DATA, write_csv

FIGURES = evaluate.RESULTS / 'figures'


def complete_rows(rows, models):
    return [r for r in rows if all(r[evaluate.COLUMN[m]] != '' for m in models)]


def reliability_bins(rows, model, n_bins=10):
    """Ten equal-width probability bins; empty bins are omitted (same rule as milestone1.py)."""
    column = evaluate.COLUMN[model]
    out = []
    for i in range(n_bins):
        group = [r for r in rows if min(n_bins - 1, int(float(r[column]) * n_bins)) == i]
        if not group:
            continue
        predicted = [float(r[column]) for r in group]
        observed = [int(r['outcome']) for r in group]
        out.append({
            'model': model,
            'label': evaluate.LABEL[model],
            'bin_lower': i / n_bins,
            'bin_upper': (i + 1) / n_bins,
            'count': len(group),
            'mean_predicted_probability': sum(predicted) / len(group),
            'observed_yes_frequency': sum(observed) / len(group),
        })
    return out


def daily_scores(rows, models):
    """Mean Brier and log loss per target date, using the same clip as evaluate.py."""
    grouped = defaultdict(list)
    for r in rows:
        grouped[r['target_date']].append(r)
    out = []
    for day in sorted(grouped):
        day_rows = grouped[day]
        n = len(day_rows)
        item = {'target_date': day, 'split': day_rows[0]['split'], 'contracts': n}
        for m in models:
            brier = log_loss = 0.0
            for r in day_rows:
                b, l = evaluate.contract_losses(float(r[evaluate.COLUMN[m]]), int(r['outcome']))
                brier += b
                log_loss += l
            item[f'{m}_brier'] = brier / n
            item[f'{m}_log_loss'] = log_loss / n
        out.append(item)
    return out


def monthly_scores(daily):
    metrics = [k for k in daily[0] if k.endswith('_brier') or k.endswith('_log_loss')] if daily else []
    months = defaultdict(lambda: {'days': 0, 'contracts': 0, 'split': set(),
                                  **{k: 0.0 for k in metrics}})
    for row in daily:
        key = row['target_date'][:7]
        bucket = months[key]
        bucket['days'] += 1
        n = row['contracts']
        bucket['contracts'] += n
        bucket['split'].add(row['split'])
        for k in metrics:
            bucket[k] += row[k] * n
    out = []
    for month in sorted(months):
        bucket = months[month]
        item = {'month': month, 'split': '+'.join(sorted(bucket['split'])),
                'days': bucket['days'], 'contracts': bucket['contracts']}
        for k in metrics:
            item[k] = bucket[k] / bucket['contracts']
        out.append(item)
    return out


def split_table(rows, models):
    table = []
    for split in ('train', 'test'):
        subset = [r for r in rows if r['split'] == split]
        result = evaluate.bootstrap(subset, models, evaluate.PAIRS)
        for m in models:
            cell = result['models'][m]
            table.append({
                'split': split,
                'model': m,
                'label': evaluate.LABEL[m],
                'days': result['days'],
                'contracts': result['contracts'],
                'brier': cell['brier']['mean'],
                'brier_ci_low': cell['brier']['ci_low'],
                'brier_ci_high': cell['brier']['ci_high'],
                'log_loss': cell['log_loss']['mean'],
                'log_loss_ci_low': cell['log_loss']['ci_low'],
                'log_loss_ci_high': cell['log_loss']['ci_high'],
            })
    return table


def _fmt(mean, lo, hi):
    return f'{mean:.4f} [{lo:.4f}, {hi:.4f}]'


def write_markdown(split_rows, monthly):
    lines = [
        '# Date comparison (generated by plot_results.py; do not edit by hand)',
        '',
        'Same contract rows as `evaluate.py` (`data/results/scored_rows.csv`): every model has a probability. '
        'Train is Aug 14, 2025 to Apr 30, 2026; test is May 1 to Aug 13, 2026. '
        'Brier and log loss use the same clip and day-level bootstrap as `evaluate.py`.',
        '',
        '### Train vs test',
        '',
        '| Split | Model | Days | Contracts | Brier [95% CI] | Log loss [95% CI] |',
        '| --- | --- | ---: | ---: | --- | --- |',
    ]
    for r in split_rows:
        lines.append(
            f"| {r['split']} | {r['label']} | {r['days']} | {r['contracts']} | "
            f"{_fmt(r['brier'], r['brier_ci_low'], r['brier_ci_high'])} | "
            f"{_fmt(r['log_loss'], r['log_loss_ci_low'], r['log_loss_ci_high'])} |"
        )
    lines += [
        '',
        '### Monthly Brier (pooled contracts)',
        '',
        '| Month | Split | Days | GEFS | Climatology | Persistence | Kalshi |',
        '| --- | --- | ---: | ---: | ---: | ---: | ---: |',
    ]
    for r in monthly:
        lines.append(
            f"| {r['month']} | {r['split']} | {r['days']} | {r['raw_ensemble_brier']:.4f} | "
            f"{r['climatology_brier']:.4f} | {r['persistence_brier']:.4f} | {r['market_brier']:.4f} |"
        )
    path = evaluate.RESULTS / 'date_comparison.md'
    path.write_text('\n'.join(lines) + '\n')
    return path


def plot_reliability(bins_by_model, title, path):
    fig, axes = plt.subplots(2, 2, figsize=(9, 8), sharex=True, sharey=True)
    for ax, (model, _) in zip(axes.ravel(), evaluate.MODELS):
        bins = bins_by_model[model]
        ax.plot([0, 1], [0, 1], color='0.6', linewidth=1, linestyle='--')
        if bins:
            x = [b['mean_predicted_probability'] for b in bins]
            y = [b['observed_yes_frequency'] for b in bins]
            s = [max(20, 8 * b['count'] ** 0.5) for b in bins]
            ax.scatter(x, y, s=s, zorder=3)
            ax.plot(x, y, linewidth=1)
        ax.set_title(evaluate.LABEL[model])
        ax.set_xlim(-0.02, 1.02)
        ax.set_ylim(-0.02, 1.02)
        ax.set_aspect('equal', adjustable='box')
    fig.suptitle(title)
    fig.supxlabel('Mean predicted probability')
    fig.supylabel('Observed YES frequency')
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_predicted_vs_actual(rows, path):
    rng = np.random.default_rng(evaluate.config.BOOTSTRAP_SEED)
    fig, axes = plt.subplots(2, 2, figsize=(9, 8), sharex=True, sharey=True)
    for ax, (model, _) in zip(axes.ravel(), evaluate.MODELS):
        p = np.array([float(r[evaluate.COLUMN[model]]) for r in rows])
        y = np.array([int(r['outcome']) for r in rows], dtype=float)
        jitter = rng.uniform(-0.04, 0.04, size=len(y))
        ax.scatter(p, y + jitter, s=8, alpha=0.25, linewidths=0)
        xs = np.linspace(0, 1, 50)
        # Running mean of outcomes in 10 bins, overlaid.
        bins = reliability_bins(rows, model)
        if bins:
            ax.plot([b['mean_predicted_probability'] for b in bins],
                    [b['observed_yes_frequency'] for b in bins],
                    color='C1', marker='o', linewidth=1.5, label='bin mean')
        ax.plot(xs, xs, color='0.6', linestyle='--', linewidth=1)
        ax.set_title(evaluate.LABEL[model])
        ax.set_xlim(-0.02, 1.02)
        ax.set_ylim(-0.12, 1.12)
        ax.set_yticks([0, 1], ['NO (0)', 'YES (1)'])
    fig.suptitle('Predicted probability vs actual YES/NO (test days)')
    fig.supxlabel('Predicted probability')
    fig.supylabel('Actual result (jittered)')
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_daily_brier(daily, path):
    dates = [np.datetime64(r['target_date']) for r in daily]
    fig, ax = plt.subplots(figsize=(11, 4.5))
    for model, label in evaluate.MODELS:
        ax.plot(dates, [r[f'{model}_brier'] for r in daily], linewidth=1, label=label)
    split_dates = [r['target_date'] for r in daily if r['split'] == 'test']
    if split_dates:
        ax.axvline(np.datetime64(split_dates[0]), color='0.3', linestyle=':', linewidth=1)
    ax.legend(ncol=4, loc='upper right', fontsize=8)
    ax.set_ylabel('Daily mean Brier')
    ax.set_title('Daily Brier score by date (train then test)')
    fig.autofmt_xdate()
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_train_vs_test(split_rows, path):
    labels = [lab for _, lab in evaluate.MODELS]
    x = np.arange(len(labels))
    width = 0.36
    fig, ax = plt.subplots(figsize=(8, 4.5))
    for i, split in enumerate(('train', 'test')):
        means = []
        yerr = []
        for m, _ in evaluate.MODELS:
            cell = next(r for r in split_rows if r['split'] == split and r['model'] == m)
            means.append(cell['brier'])
            yerr.append([cell['brier'] - cell['brier_ci_low'], cell['brier_ci_high'] - cell['brier']])
        ax.bar(x + (i - 0.5) * width, means, width, yerr=np.array(yerr).T, capsize=3, label=split)
    ax.set_xticks(x, labels)
    ax.set_ylabel('Brier score')
    ax.set_title('Train vs test Brier (day-bootstrap 95% intervals)')
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_monthly_brier(monthly, path):
    months = [r['month'] for r in monthly]
    x = np.arange(len(months))
    fig, ax = plt.subplots(figsize=(11, 4.5))
    for model, label in evaluate.MODELS:
        ax.plot(x, [r[f'{model}_brier'] for r in monthly], marker='o', linewidth=1.5, label=label)
    test_start = next((i for i, r in enumerate(monthly) if 'test' in r['split'] and 'train' not in r['split']), None)
    if test_start is not None:
        ax.axvline(test_start - 0.5, color='0.3', linestyle=':', linewidth=1)
    ax.set_xticks(x, months, rotation=45, ha='right')
    ax.set_ylabel('Monthly mean Brier')
    ax.set_title('Monthly Brier by date (Apr→May is the train/test cut)')
    ax.legend(ncol=4, fontsize=8)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def main():
    rows = evaluate.read_csv(evaluate.RESULTS / 'scored_rows.csv')
    models = [m for m, _ in evaluate.MODELS]
    shared = complete_rows(rows, models)
    test_rows = [r for r in shared if r['split'] == 'test']
    if not test_rows:
        raise SystemExit('No complete test rows in data/results/scored_rows.csv; run evaluate.py first.')

    FIGURES.mkdir(parents=True, exist_ok=True)
    daily = daily_scores(shared, models)
    monthly = monthly_scores(daily)
    splits = split_table(shared, models)
    reliability = []
    bins_test = {}
    for m in models:
        bins_test[m] = reliability_bins(test_rows, m)
        for row in bins_test[m]:
            reliability.append({**row, 'split': 'test'})
        for row in reliability_bins([r for r in shared if r['split'] == 'train'], m):
            reliability.append({**row, 'split': 'train'})

    write_csv('results/daily_scores.csv', daily)
    write_csv('results/monthly_scores.csv', monthly)
    write_csv('results/train_vs_test.csv', splits)
    write_csv('results/reliability_by_split.csv', reliability)
    md = write_markdown(splits, monthly)

    plot_reliability(bins_test, 'Predicted probability vs realized YES rate (test days)',
                     FIGURES / 'reliability_test.png')
    plot_predicted_vs_actual(test_rows, FIGURES / 'predicted_vs_actual_test.png')
    plot_daily_brier(daily, FIGURES / 'daily_brier_by_date.png')
    plot_train_vs_test(splits, FIGURES / 'train_vs_test_brier.png')
    plot_monthly_brier(monthly, FIGURES / 'monthly_brier.png')

    print(md.read_text())
    print('Wrote figures to', FIGURES)


if __name__ == '__main__':
    main()
