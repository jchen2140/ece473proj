"""Collect the frozen conservative-truncation rule across every city it was run on.

Reads data/results/conservative_truncation/<city>/ written by market.conservative (run with --cities ...)
and adds two sensor diagnostics per city: days where the 1-minute maximum exceeded the official high by
2F or more (enough to write off a winning bin), and the largest such error. Cities whose training data fail
the predeclared coverage rule are listed, not dropped silently. Writes six_city_summary.{csv,md}.
"""
import sys

import pandas as pd

from market import conservative, cross_city, makers

OUT = conservative.OUT


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    rows, missing = [], []
    for code in makers.REALTIME_CITIES:
        if not (OUT / code / 'daily.csv').exists():
            missing.append(code)
            continue
        summary, paired = cross_city.compare_city(code)
        audit = pd.read_csv(OUT / code / 'sensor_audit.csv')
        err = audit['sensor_minus_official_f'].dropna()
        by = {r['variant']: r for r in summary}
        weekly = {(p['second'], p['metric']): p for p in paired if p['bootstrap_block_days'] == 7}
        for variant, r in by.items():
            rows.append({**r, 'sensor_error_2f_days': int((err >= 2).sum()), 'audited_days': int(len(err)),
                         'max_sensor_error_f': float(err.max()),
                         **({f'cons_minus_{o}_{m}': weekly[o, m]['mean_difference'] for o in ('current_truncation', 'forecast_only')
                             for m in ('mean_net_pnl', 'worst_5pct_mean_pnl')} if variant == 'conservative_truncation' else {}),
                         **({f'cons_minus_{o}_{m}_ci': (weekly[o, m]['ci_low'], weekly[o, m]['ci_high'])
                             for o in ('current_truncation', 'forecast_only') for m in ('mean_net_pnl', 'worst_5pct_mean_pnl')}
                            if variant == 'conservative_truncation' else {})})
    d = pd.DataFrame(rows)  # Rows have different keys, so let pandas take the union of columns.
    d.to_csv(OUT / 'six_city_summary.csv', index=False)
    lines = ['# Conservative truncation across cities (generated by market/conservative_summary.py; do not edit by hand)', '',
             'Frozen rule from docs/CONSERVATIVE_TRUNCATION.md: margin = nearest-rank 99th percentile of positive training '
             'sensor-minus-official errors, rounded up to 0.5F; 80% minute coverage; 5-minute feed delay; common b and fee from '
             'forecast-only training PnL. Each city fits its own margin. Test days Jun 1 - Aug 13, 2026, coverage-qualified.', '',
             '| City | Margin | Test days | Forecast only | Current truncation | Conservative | Current: winner written off | '
             'Conservative: winner written off | Sensor >= 2F over official (days) | Largest sensor error |',
             '| --- | ---: | ---: | --- | --- | --- | ---: | ---: | ---: | ---: |']

    def cell(r):
        return f"${r['mean_pnl']:,.0f} (worst ${r['worst_day']:,.0f})".replace('$-', '-$')

    for code, g in d.groupby('city', sort=False):
        v = g.set_index('variant')
        f, c, k = v.loc['forecast_only'], v.loc['current_truncation'], v.loc['conservative_truncation']
        lines.append(f"| {code} | {k['margin_f']:g}F | {int(k['test_days'])} | {cell(f)} | {cell(c)} | {cell(k)} | "
                     f"{int(c['incorrectly_heavily_discounted_winner_days'])} | {int(k['incorrectly_heavily_discounted_winner_days'])} | "
                     f"{int(k['sensor_error_2f_days'])}/{int(k['audited_days'])} | {k['max_sensor_error_f']:+.0f}F |")
    lines += ['', 'Mean PnL per test day, worst test day in brackets. "Written off" = the winning bin was weighted 0.001.', '',
              '| City | Conservative minus current: mean [95% CI] | Conservative minus current: worst-5% mean [95% CI] | '
              'Conservative minus forecast only: mean [95% CI] |', '| --- | --- | --- | --- |']
    for _, r in d[d['variant'] == 'conservative_truncation'].iterrows():
        def fmt(key):
            lo, hi = r[key + '_ci']
            return f"{r[key]:+,.0f} [{lo:+,.0f}, {hi:+,.0f}]"
        lines.append(f"| {r['city']} | {fmt('cons_minus_current_truncation_mean_net_pnl')} | "
                     f"{fmt('cons_minus_current_truncation_worst_5pct_mean_pnl')} | {fmt('cons_minus_forecast_only_mean_net_pnl')} |")
    lines += ['', 'Paired 7-day calendar-block bootstrap, 1,000 resamples.', '']
    if missing:
        lines += [f"Not evaluable under the frozen coverage rule (fewer than 20 training days with 80% of minutes present): "
                  f"{', '.join(missing)}.", '']
    lines += ['## Caveats', '',
              '- NYC motivated the rule and CHI was a registered replication; LAX, AUS and MSP were run afterwards with the rule '
              'unchanged. Unguarded results for every city had been seen before.',
              '- With 20-45 training days the 99th percentile is the largest training error, so a single bad reading sets the '
              'margin. In LAX a 120F reading on a 68F day (May 24) gives a 52F margin, which switches truncation off; the frozen '
              'rule has no plausibility filter and we did not add one after seeing this.',
              '- Counterfactual replay; hypothetical maker fee; feed delay is a proxy.']
    text = '\n'.join(lines) + '\n'
    (OUT / 'six_city_summary.md').write_text(text, encoding='utf-8')
    print(text)


if __name__ == '__main__':
    main()
